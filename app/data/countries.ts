export function countryFlag(alpha2: string): string {
  return [...alpha2.toUpperCase()]
    .map((c) => String.fromCodePoint(0x1f1e6 + c.charCodeAt(0) - 65))
    .join("")
}

export const countryByNumeric: Map<string, CountryInfo> = new Map(
  countries.map((c) => [c.numeric, c]),
)

export const countryByAlpha2: Map<string, CountryInfo> = new Map(
  countries.map((c) => [c.alpha2, c]),
)

export const TOTAL_COUNTRIES: number = countries.length

export const regions: string[] = [...new Set(countries.map((c) => c.region))].toSorted()

export function countryCenter(
  code: string | null | undefined,
): { lat: number; lng: number } | null {
  if (!code) return null
  const c = countryByAlpha2.get(code.toUpperCase())
  return c ? { lat: c.lat, lng: c.lng } : null
}

export function countryZoom(code: string | null | undefined): number | null {
  if (!code) return null
  return countryByAlpha2.get(code.toUpperCase())?.zoom ?? null
}

export function countryCurrency(code: string | null | undefined): string | null {
  if (!code) return null
  return countryByAlpha2.get(code.toUpperCase())?.currency ?? null
}

export function countryName(code: string | null | undefined): string | null {
  if (!code) return null
  return countryByAlpha2.get(code.toUpperCase())?.name ?? null
}

export function isCountryCode(code: string | null | undefined): boolean {
  if (!code || typeof code !== "string") return false
  return countryByAlpha2.has(code.toUpperCase())
}
